package com.footballbounce.server.domain;

public class PlayerData {
    private String playerId;
    private String name;
    private Integer score;
    private String rarity;
    private Integer avatarSeed;
    private String intro;
    private String bodyType;
    private String nationality;
    private String club;
    private Integer height;
    private Integer weight;
    private Integer age;
    private String skills;
    private Integer power;
    private Integer accuracy;
    private Integer curve;
    private Integer stamina;
    private Integer bodyStrength;

    public String getPlayerId() { return playerId; }
    public void setPlayerId(String playerId) { this.playerId = playerId; }
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    public Integer getScore() { return score; }
    public void setScore(Integer score) { this.score = score; }
    public String getRarity() { return rarity; }
    public void setRarity(String rarity) { this.rarity = rarity; }
    public Integer getAvatarSeed() { return avatarSeed; }
    public void setAvatarSeed(Integer avatarSeed) { this.avatarSeed = avatarSeed; }
    public String getIntro() { return intro; }
    public void setIntro(String intro) { this.intro = intro; }
    public String getBodyType() { return bodyType; }
    public void setBodyType(String bodyType) { this.bodyType = bodyType; }
    public String getNationality() { return nationality; }
    public void setNationality(String nationality) { this.nationality = nationality; }
    public String getClub() { return club; }
    public void setClub(String club) { this.club = club; }
    public Integer getHeight() { return height; }
    public void setHeight(Integer height) { this.height = height; }
    public Integer getWeight() { return weight; }
    public void setWeight(Integer weight) { this.weight = weight; }
    public Integer getAge() { return age; }
    public void setAge(Integer age) { this.age = age; }
    public String getSkills() { return skills; }
    public void setSkills(String skills) { this.skills = skills; }
    public Integer getPower() { return power; }
    public void setPower(Integer power) { this.power = power; }
    public Integer getAccuracy() { return accuracy; }
    public void setAccuracy(Integer accuracy) { this.accuracy = accuracy; }
    public Integer getCurve() { return curve; }
    public void setCurve(Integer curve) { this.curve = curve; }
    public Integer getStamina() { return stamina; }
    public void setStamina(Integer stamina) { this.stamina = stamina; }
    public Integer getBodyStrength() { return bodyStrength; }
    public void setBodyStrength(Integer bodyStrength) { this.bodyStrength = bodyStrength; }
}
